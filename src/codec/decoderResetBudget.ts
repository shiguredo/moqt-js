/**
 * 映像デコーダーの再初期化に使う復帰予算
 *
 * 恒久エラーでデコーダーを再初期化し続けると、Worker の生成と破棄が止まらなくなる。
 * 「同じ設定で、復号フレームを 1 枚も出力しないまま再初期化した回数」を数え、
 * 上限を超える再初期化を拒否するための純粋クラスである。
 *
 * 予算は再初期化の試行で消費する (成功の数ではない)。configure が失敗した場合も
 * 1 回分消費する。予算を戻す (消費を 0 にする) 機会は 2 つだけである。
 *
 * - configure が直前と参照の異なる設定を受け取ったとき
 * - 復号フレームを 1 枚出力したとき
 *
 * 再初期化の再入 (同じ設定での reset()) では戻さない。戻すと上限が無効になり、
 * 恒久エラーで再生成が止まらない。
 *
 * ブラウザ API に依存しないため、Node の単体テストで固定する。
 */

/**
 * 復号フレームを得ないまま再初期化できる回数の上限
 *
 * 上限に達したら再初期化を打ち切る。一時的なエラーからの復帰 (再初期化 1 回で
 * 復号が再開する場合) は妨げない値にする。上限そのものが契約であり、
 * モジュール外から参照しない (上限を使う判定は DecoderResetBudget が持つ)。
 */
const DECODER_RESET_LIMIT = 3;

/**
 * 復帰予算
 *
 * 消費した再初期化の回数を数え、上限に達したら tryConsume() が false を返す。
 * 消費は 0 未満にならない (上限に達した後は数え続けない)。
 */
export class DecoderResetBudget {
  // 消費した回数 (0 以上 DECODER_RESET_LIMIT 以下)
  private consumedCount = 0;

  /**
   * 再初期化を 1 回試す
   *
   * 予算が残っていれば 1 回分消費して true を返す。使い切っていれば何も消費せず
   * false を返す (消費は 0 未満にならない)。
   *
   * @returns 再初期化してよい場合は true
   */
  tryConsume(): boolean {
    if (this.consumedCount >= DECODER_RESET_LIMIT) {
      return false;
    }
    this.consumedCount += 1;
    return true;
  }

  /**
   * 予算を戻す (消費した回数を 0 にする)
   *
   * 参照の異なる設定での configure と、復号フレームの出力から呼ぶ。
   */
  restore(): void {
    this.consumedCount = 0;
  }
}
